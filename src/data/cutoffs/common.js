// Get all university names
export const getUniversities = () => Object.keys(COMMON_CUTOFFS).sort()

// Get all courses for a university
export const getCourses = (university) => {
  return COMMON_CUTOFFS[university] ? Object.keys(COMMON_CUTOFFS[university]).sort() : []
}

// Check if data exists
export const hasData = (university, course) => {
  return COMMON_CUTOFFS[university]?.[course] !== undefined
}

// Get full data for a specific university and course
export const getCutoffData = (university, course) => {
  const data = COMMON_CUTOFFS[university]?.[course]
  if (!data) return null
  
  const formatted = []
  for (let i = 0; i < data.length; i += 2) {
    formatted.push({ year: data[i], value: data[i+1] })
  }
  return formatted
}

// Get the latest cut-off for a university and course
export const getLatestCutoff = (university, course) => {
  const data = COMMON_CUTOFFS[university]?.[course]
  if (!data || data.length < 2) return null
  return { year: data[0], value: data[1] }
}

// Get all courses across all universities
export const getAllCourses = () => {
  const courses = new Set()
  Object.values(COMMON_CUTOFFS).forEach(uni => {
    Object.keys(uni).forEach(course => courses.add(course))
  })
  return Array.from(courses).sort()
}

// Search universities by name
export const searchUniversities = (query) => {
  const q = query.toLowerCase().trim()
  if (!q) return getUniversities()
  return getUniversities().filter(uni => uni.toLowerCase().includes(q))
}

// Search courses by name
export const searchCourses = (query) => {
  const q = query.toLowerCase().trim()
  if (!q) return getAllCourses()
  return getAllCourses().filter(course => course.toLowerCase().includes(q))
}

// Get summary statistics for a university
export const getUniversityStats = (university) => {
  const uniData = COMMON_CUTOFFS[university]
  if (!uniData) return null
  
  const courses = Object.keys(uniData)
  const totalCourses = courses.length
  const highestCutoff = Math.max(...courses.map(c => uniData[c][1] || 0))
  const lowestCutoff = Math.min(...courses.map(c => uniData[c][1] || Infinity))
  
  // Get top 3 highest courses
  const topCourses = courses
    .map(c => ({ name: c, cutoff: uniData[c][1] || 0 }))
    .sort((a, b) => b.cutoff - a.cutoff)
    .slice(0, 3)
  
  return {
    totalCourses,
    highestCutoff,
    lowestCutoff,
    topCourses
  }
}

// Get recommended courses based on score
export const getRecommendedCourses = (score, university) => {
  const uniData = COMMON_CUTOFFS[university]
  if (!uniData) return []
  
  const recommendations = []
  Object.entries(uniData).forEach(([course, data]) => {
    const cutoff = data[1] || 0
    const difference = score - cutoff
    recommendations.push({
      course,
      cutoff,
      difference,
      status: difference >= 0 ? 'Likely' : 'Unlikely'
    })
  })
  
  return recommendations.sort((a, b) => b.difference - a.difference)
}