// ============================================================
// HELPER FUNCTIONS
// ============================================================

// Get all elements
export const getAllElements = () => Object.values(PERIODIC_TABLE)

// Get element by symbol
export const getElementBySymbol = (symbol) => {
  return PERIODIC_TABLE[symbol] || null
}

// Get element by atomic number
export const getElementByNumber = (number) => {
  for (const [symbol, data] of Object.entries(PERIODIC_TABLE)) {
    if (data.atomicNumber === number) {
      return { symbol, ...data }
    }
  }
  return null
}

// Get elements by category
export const getElementsByCategory = (category) => {
  return Object.entries(PERIODIC_TABLE)
    .filter(([_, data]) => data.category === category)
    .map(([symbol, data]) => ({ symbol, ...data }))
}

// Get elements by period
export const getElementsByPeriod = (period) => {
  return Object.entries(PERIODIC_TABLE)
    .filter(([_, data]) => data.period === period)
    .map(([symbol, data]) => ({ symbol, ...data }))
}

// Get elements by group
export const getElementsByGroup = (group) => {
  return Object.entries(PERIODIC_TABLE)
    .filter(([_, data]) => data.group === group)
    .map(([symbol, data]) => ({ symbol, ...data }))
}

// Get all categories
export const getCategories = () => {
  const categories = new Set()
  Object.values(PERIODIC_TABLE).forEach(data => {
    categories.add(data.category)
  })
  return Array.from(categories).sort()
}

// Search elements by name
export const searchElements = (query) => {
  const q = query.toLowerCase().trim()
  if (!q) return getAllElements()
  
  return Object.entries(PERIODIC_TABLE)
    .filter(([symbol, data]) => 
      data.name.toLowerCase().includes(q) ||
      symbol.toLowerCase().includes(q) ||
      String(data.atomicNumber).includes(q)
    )
    .map(([symbol, data]) => ({ symbol, ...data }))
}

// Get element state at room temperature
export const getElementsByState = (state) => {
  return Object.entries(PERIODIC_TABLE)
    .filter(([_, data]) => data.state === state)
    .map(([symbol, data]) => ({ symbol, ...data }))
}

// Get elements discovered after a certain year
export const getElementsDiscoveredAfter = (year) => {
  return Object.entries(PERIODIC_TABLE)
    .filter(([_, data]) => {
      if (data.yearDiscovered === "Ancient") return false
      return data.yearDiscovered > year
    })
    .map(([symbol, data]) => ({ symbol, ...data }))
    .sort((a, b) => a.yearDiscovered - b.yearDiscovered)
}

// Get element summary
export const getElementSummary = (symbol) => {
  const element = getElementBySymbol(symbol)
  if (!element) return null
  
  return {
    symbol: element.symbol,
    name: element.name,
    atomicNumber: element.atomicNumber,
    atomicMass: element.atomicMass,
    category: element.category,
    state: element.state,
    description: element.description
  }
}

// Get electronic configuration
export const getElectronConfig = (symbol) => {
  const element = getElementBySymbol(symbol)
  return element ? element.electronConfiguration : null
}

// Get period table statistics
export const getTableStats = () => {
  const elements = getAllElements()
  
  return {
    totalElements: elements.length,
    categories: getCategories().map(cat => ({
      name: cat,
      count: elements.filter(el => el.category === cat).length
    })),
    periods: [...new Set(elements.map(el => el.period))].map(p => ({
      period: p,
      count: elements.filter(el => el.period === p).length
    })),
    states: {
      gas: elements.filter(el => el.state === "Gas").length,
      liquid: elements.filter(el => el.state === "Liquid").length,
      solid: elements.filter(el => el.state === "Solid").length
    },
    discovered: {
      ancient: elements.filter(el => el.yearDiscovered === "Ancient").length,
      modern: elements.filter(el => el.yearDiscovered !== "Ancient").length
    }
  }
}